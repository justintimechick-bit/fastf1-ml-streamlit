"""Prediction always checks model lineage and the selected information cutoff."""

from pathlib import Path

import joblib
import pandas as pd

from f1ml.domain import utc
from f1ml.features.build import build_event
from f1ml.ingestion.pipeline import Dataset
from f1ml.models.baseline import ModelArtifact, predict
from f1ml.storage import new_directory, save_table, seal_directory


def predict_checked(artifact: ModelArtifact, features: pd.DataFrame, manifest: dict):
    if artifact.metadata["manifest_id"] != manifest["id"]:
        raise ValueError("Model was trained against a different frozen manifest")
    if set(features.event_id) & set(manifest["final_test"]):
        raise ValueError("Final test block is sealed during this phase")
    if set(features.event_id) & set(artifact.metadata["train_events"]):
        raise ValueError("Prediction event was part of this model's training fold")
    earliest = min(utc(t) for t in features.cutoff)
    if utc(artifact.metadata["max_feature_cutoff"]) >= earliest:
        raise ValueError("Training features are not strictly earlier than prediction cutoff")
    if utc(artifact.metadata["max_label_end"]) >= earliest:
        raise ValueError("Training labels are not earlier than prediction cutoff")
    if features["mode"].eq("publication_snapshot").any():
        if artifact.metadata["modes"] != ["publication_snapshot"]:
            raise ValueError("A reconstructed model cannot claim publication snapshot evaluation")
        if utc(artifact.metadata["max_label_retrieved_at"]) > earliest:
            raise ValueError("Training label revision was downloaded after prediction cutoff")
    return predict(artifact, features)


def predict_event(
    artifact: ModelArtifact,
    dataset: Dataset,
    manifest: dict,
    event_id: str,
    cutoff,
    entrants: pd.DataFrame,
    mode: str,
    output: Path,
):
    task = "race" if artifact.task == "podium" else artifact.task
    features, audit = build_event(
        dataset, manifest, event_id, task, cutoff, entrants, mode, inference=True
    )
    predictions = predict_checked(artifact, features, manifest)
    new_directory(output)
    save_table(output / "predictions.parquet", predictions)
    return seal_directory(
        output,
        {
            "manifest_id": manifest["id"],
            "prediction_dataset_id": dataset.receipt["id"],
            "task": artifact.task,
            "model": artifact.metadata,
            "audit": audit,
        },
    )


def load_model(path: Path) -> ModelArtifact:
    # joblib uses pickle: only load artifacts generated by this project that you trust.
    artifact = joblib.load(path)
    if not isinstance(artifact, ModelArtifact):
        raise ValueError("Unsupported model artifact")
    return artifact
